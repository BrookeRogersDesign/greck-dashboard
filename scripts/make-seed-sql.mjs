// Prints supabase/seed.sql from src/seed.js:  npm run seed-sql
import { phases, milestones, tasks, links, log } from '../src/seed.js';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const rows = (table, cols, items) =>
  `insert into ${table} (${cols.join(', ')}) values\n` +
  items.map((it) => `  (${cols.map((c) => q(it[c])).join(', ')})`).join(',\n') + ';\n';

console.log(`-- Generated by scripts/make-seed-sql.mjs. Run after schema.sql.
-- Clears existing data first.
truncate log, links, assets, tasks, milestones, phases;

-- Change these passcodes! (Or run dash_set_passcode again later.)
select dash_set_passcode('brooke', 'change-me-brooke');
select dash_set_passcode('kenzie', 'change-me-kenzie');
`);
console.log(rows('phases', ['id', 'name', 'tag', 'target_label', 'target_date', 'sort'], phases));
console.log(rows('milestones', ['label', 'date', 'end_date', 'done', 'sort'], milestones));
console.log(rows('tasks', ['title', 'phase_id', 'section', 'owner', 'due_date', 'status', 'notes', 'sort'], tasks));
console.log(rows('links', ['label', 'url', 'sort'], links));
console.log(rows('log', ['author', 'kind', 'body', 'created_at'], log));
